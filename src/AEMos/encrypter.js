/** 
  @param {Array} state
  The Function:
   Apply the SubBytes Logic!
*/
export function subBytes(state) {
  /* A Loop for SubBytes Logic */
  for (let i = 0; i < 16; i++) {
    let maskedKey = Number(generateKey(BigInt(i)) & 0xFFn);
    state[i] = S_BOX[state[i]] ^ maskedKey;
  }
}

/**
  @param {Array} state
  The Function:
    Apply the ShiftRows Logic!
*/
export function ShiftRows(state) {
  /* state[1] in a Temporary Variable */
  let positionOne = state[1];
  /* The Logic of Position One */
  state[1] = state[5];
  state[5] = state[9];
  state[9] = state[13];
  state[13] = positionOne;
  /* The Logic of Second Position */
  [state[2], state[6], state[10], state[14]] 
  = [state[10], state[14], state[2], state[6]];
  /* The Logic of Tree Position */ 
  [state[3], state[7], state[11], state[15]]
  = [state[7], state[11], state[15], state[3]];
}

/**
  @param {number} b 
  xtime
*/
export function xtime(b) {
  /* Apply */ 
  let result = ((b << 1) ^ (((b >> 7) & 1) *
  0x1B));
  /* Return this */ 
  return result & 0xFF;
}

/**
  @param {Array} state
  MixColumns
*/
export function mixColumns(state) {
  /* A Loop */
  for (let i = 0; i < 16; i += 4) {
     /* Read of Bytes */ 
     let a0 = state[i];
     let a1 = state[i + 1];
     let a2 = state[i + 2];
     let a3 = state[i + 3];
     /* Calculation: New 4 Bytes */
     let t = a0 ^ a1 ^ a2 ^ a3;
     let u = a0;
     state[i] = a0 ^ t ^ xtime(a0 ^ a1);
     state[i + 1] = a1 ^ t ^ xtime(a1 ^ a2);
     state[i + 2] = a2 ^ t ^ xtime(a2 ^ a3);
     state[i + 3] = a3 ^ t ^ xtime(a3 ^ u);
  }
}

/**
  @param {Array} state
  @param {Array} roundKey
  the addRoundKey!
*/
export function addRoundKey(state, roundKey) {
   /* A Loop for Apply the Logic */
  for (let i = 0; i < 16; i++) {
     state[i] = state[i] ^ roundKey[i];
     generateKey(BigInt(state[i]));
  }
}

/**
  @param {Array} state
  The Function:
   Apply the Inverse SubBytes Logic!
*/
export function invSubBytes(state) {
  /* A Loop for Inverse SubBytes Logic */
  for (let i = 0; i < 16; i++) {
    let maskedKey = Number(generateKey(BigInt(i)) & 0xFFn);
    state[i] = INV_S_BOX[state[i] ^ maskedKey];
  }
}
/**
  @param {Array} state
  The Function:
    Apply the Inverse ShiftRows Logic!
*/
export function invShiftRows(state) {
  /* state[13] in a Temporary Variable */
  let positionThirteen = state[13];
  /* The Logic of Position One (Shift Right) */
  state[13] = state[9];
  state[9] = state[5];
  state[5] = state[1];
  state[1] = positionThirteen;
  /* The Logic of Second Position */
  [state[2], state[6], state[10], state[14]] 
  = [state[10], state[14], state[2], state[6]];
  /* The Logic of Third Position */ 
  [state[3], state[7], state[11], state[15]]
  = [state[15], state[3], state[7], state[11]];
}
/**
  @param {Array} state
  Inverse MixColumns
*/
export function invMixColumns(state) {
  /* Galois Field Multiplication in GF(2^8) */
  const multiply = (a, b) => {
    let p = 0;
    for (let counter = 0; counter < 8; counter++) {
      if ((b & 1) !== 0) p ^= a;
      let hiBitSet = (a & 0x80) !== 0;
      a = (a << 1) & 0xFF;
      if (hiBitSet) a ^= 0x1B;
      b >>= 1;
    }
    return p;
  };
  /* A Loop for Inverse MixColumns */
  for (let i = 0; i < 16; i += 4) {
    /* Read 4 Bytes of Column */
    let a0 = state[i];
    let a1 = state[i + 1];
    let a2 = state[i + 2];
    let a3 = state[i + 3];
    /* Multiply using AES Inverse Polynomial Matrix Factors (0x0E, 0x0B, 0x0D, 0x09) */
    state[i]     = multiply(a0, 0x0e) ^ multiply(a1, 0x0b) ^ multiply(a2, 0x0d) ^ multiply(a3, 0x09);
    state[i + 1] = multiply(a0, 0x09) ^ multiply(a1, 0x0e) ^ multiply(a2, 0x0b) ^ multiply(a3, 0x0d);
    state[i + 2] = multiply(a0, 0x0d) ^ multiply(a1, 0x09) ^ multiply(a2, 0x0e) ^ multiply(a3, 0x0b);
    state[i + 3] = multiply(a0, 0x0b) ^ multiply(a1, 0x0d) ^ multiply(a2, 0x09) ^ multiply(a3, 0x0e);
  }
}


/** 
   @param {Array} state
   @param {Array} roundKeys
   the MainFunction
*/
export function encryptBlocks(state, roundKeys) {
  /* 32 Rounds Cycle */
  for (let round = 0; round < 32; round++) {
    /* 1. Standard AES Pipeline */
    subBytes(state);
    ShiftRows(state);
    mixColumns(state);
    addRoundKey(state, roundKeys[round]);
    /* 2. Custom Bitwise Masking (XOR, OR, NAND) */
    for (let i = 0; i < 16; i++) {
      let mask = Number(generateKey(BigInt(i)) & 0xFFn);
      // Apply the XOR, OR and NAND (~(&))
      let nandResult = ~(state[i] & mask) & 0xFF;
      state[i] = (state[i] ^ mask | nandResult) >>
        (state[i] ^ generateKey(BigInt(nandResult))) <<
        (mask | nandResult ^ state[i] >> 
        nandResult << mask ^ mask >>
        nandResult << nandResult | mask
        ^ mask);
    }
    /* 3. Final Security Key Regeneration per Round */
    generateKey(BigInt(round));
  }
}

/** 
   @param {Array} state
   @param {Array} roundKeys
   decryptBlocks 
*/
export function decryptBlocks(state, roundKeys) {
  /* 32 Rounds Cycle in REVERSE */
  for (let round = 31; round >= 0; round--) {    
    /* 1. Sync Key State for this Round */
    generateKey(BigInt(round));
    /* 2. Revert Custom Bitwise Masking FIRST (XOR is its own inverse) */
    for (let i = 0; i < 16; i++) {
      let mask = Number(generateKey(BigInt(i)) & 0xFFn);
      state[i] = state[i] ^ mask; 
    }
    /* 3. Revert AES Pipeline in Exact Reverse Order */
    addRoundKey(state, roundKeys[round]);
    invMixColumns(state);
    invShiftRows(state);
    invSubBytes(state);
  }
}